"""Generate ready-to-use CSS type scales (modular ratios) and Utopia-style fluid clamp() scales.
Fluid math is a Python port of trys/utopia-core (ISC) calculateClamp/calculateTypeStep/calculateSpaceSize.
Usage: python3 -I util_type_scales.py <out_dir>"""
import json, os, sys
out = sys.argv[1]
os.makedirs(os.path.join(out, "typescale"), exist_ok=True)
os.makedirs(os.path.join(out, "utopia", "fluid"), exist_ok=True)

RATIOS = {"1.125": "major-second", "1.2": "minor-third", "1.25": "major-third", "1.333": "perfect-fourth",
          "1.414": "augmented-fourth", "1.5": "perfect-fifth", "1.618": "golden-ratio"}
LABELS = {-2: "xs", -1: "sm", 0: "base", 1: "lg", 2: "xl", 3: "2xl", 4: "3xl", 5: "4xl", 6: "5xl"}
HEADINGS = {"h1": 6, "h2": 5, "h3": 4, "h4": 3, "h5": 2, "h6": 1}
r4 = lambda n: round(n + 1e-12, 4)
fmt = lambda n: f"{r4(n):g}"

table = {}
for ratio, name in RATIOS.items():
    q = float(ratio); rows = {}
    lines = [f"/* Type scale {ratio} ({name}) — base 1rem (16px). Generated by ui-library/scripts/util_type_scales.py */",
             f"/* Use: <link rel=\"stylesheet\" href=\"type-scale-{ratio}.css\"> then use var(--fs-xl) ... */", ":root {",
             f"  --type-ratio: {ratio};"]
    for step in range(-2, 7):
        rem = q ** step; rows[LABELS[step]] = {"step": step, "rem": r4(rem), "px": round(rem * 16, 2)}
        lines.append(f"  --fs-{LABELS[step]}: {fmt(rem)}rem; /* step {step} ≈ {rem*16:.2f}px */")
    lines += ["  --lh-tight: 1.15;", "  --lh-normal: 1.6;", "}", "",
              "/* Add the .type-scale class to <body> (or a wrapper element) to apply it to headings and paragraphs */",
              ".type-scale { font-size: var(--fs-base); line-height: var(--lh-normal); }"]
    for h, st in HEADINGS.items():
        lines.append(f".type-scale {h} {{ font-size: var(--fs-{LABELS[st]}); line-height: var(--lh-tight); }}")
    lines += [".type-scale small { font-size: var(--fs-sm); }", ""]
    open(os.path.join(out, "typescale", f"type-scale-{ratio}.css"), "w").write("\n".join(lines))
    table[ratio] = {"name": name, "base_px": 16, "steps": rows}
json.dump(table, open(os.path.join(out, "typescale", "modular-scales.json"), "w"), ensure_ascii=False, indent=1)

# ---------- Utopia port ----------
def calc_clamp(min_size, max_size, min_w, max_w, use_px=False, unit_rel="vi"):
    lo, hi = sorted([min_size, max_size])
    d = 1 if use_px else 16; u = "px" if use_px else "rem"
    slope = (max_size / d - min_size / d) / (max_w / d - min_w / d)
    inter = -1 * (min_w / d) * slope + min_size / d
    return f"clamp({fmt(lo/d)}{u}, {fmt(inter)}{u} + {fmt(slope*100)}{unit_rel}, {fmt(hi/d)}{u})"

def rng(x1, y1, x2, y2, a):
    t = min(1, max(0, (a - x1) / (y1 - x1))); return x2 * (1 - t) + y2 * t

def fluid_type(cfg):
    res = []
    for step in list(range(cfg["pos"], 0, -1)) + [0] + [-i for i in range(1, cfg["neg"] + 1)]:
        def size(vw):
            return rng(cfg["minW"], cfg["maxW"], cfg["minFS"], cfg["maxFS"], vw) * rng(cfg["minW"], cfg["maxW"], cfg["minR"], cfg["maxR"], vw) ** step
        res.append((step, size(cfg["minW"]), size(cfg["maxW"])))
    return res

SPACE_NEG = [(0.75, -1, "xs"), (0.5, -2, "2xs"), (0.25, -3, "3xs")]
SPACE_POS = [(1.5, 1, "m"), (2, 2, "l"), (3, 3, "xl"), (4, 4, "2xl"), (6, 5, "3xl")]

def fluid_space(cfg):
    sizes = [(m, s, l) for (m, s, l) in reversed(SPACE_NEG)] + [(1, 0, "s")] + SPACE_POS
    out_ = []
    for m, s, l in sizes:
        out_.append((l, int(cfg["minFS"] * m + 0.5), int(cfg["maxFS"] * m + 0.5)))  # JS Math.round
    return out_  # ascending

PRESETS = {
    "utopia-default": {"minW": 320, "maxW": 1240, "minFS": 18, "maxFS": 20, "minR": 1.2, "maxR": 1.25, "pos": 5, "neg": 2,
                       "note": "utopia.fyi default settings: screen 320→1240px, base text 18→20px, ratio 1.2→1.25"},
    "compact": {"minW": 360, "maxW": 1280, "minFS": 16, "maxFS": 18, "minR": 1.125, "maxR": 1.2, "pos": 5, "neg": 2,
                "note": "Compact, for web apps/dashboards: text 16→18px, ratio 1.125→1.2"},
    "editorial": {"minW": 360, "maxW": 1440, "minFS": 18, "maxFS": 21, "minR": 1.25, "maxR": 1.333, "pos": 6, "neg": 2,
                  "note": "For landing pages/blogs: larger headings, ratio 1.25→1.333"},
}
TYPE_LABEL = {-2: "xs", -1: "sm", 0: "base", 1: "lg", 2: "xl", 3: "2xl", 4: "3xl", 5: "4xl", 6: "5xl"}
summary = {}
for key, c in PRESETS.items():
    t = fluid_type(c); s = fluid_space(c)
    L = [f"/* Fluid type + space ({key}) — {c['note']}.",
         f"   Port of the utopia-core formulas (ISC, trys/utopia-core). Viewport {c['minW']}px → {c['maxW']}px.",
         "   Use: font-size: var(--step-2); padding: var(--space-s-m); gap: var(--space-m); */", ":root {"]
    for step, lo, hi in t:
        L.append(f"  --step-{step}: {calc_clamp(lo, hi, c['minW'], c['maxW'])}; /* {lo:.2f}px → {hi:.2f}px */")
    L.append("")
    for label, lo, hi in s:
        L.append(f"  --space-{label}: {calc_clamp(lo, hi, c['minW'], c['maxW'])}; /* {lo}px → {hi}px */")
    L.append("\n  /* One-up pairs: scale more strongly (e.g. --space-s-m: s when small, m when large) */")
    for (l1, lo1, _), (l2, _, hi2) in zip(s, s[1:]):
        L.append(f"  --space-{l1}-{l2}: {calc_clamp(lo1, hi2, c['minW'], c['maxW'])};")
    sm = dict((l, (lo, hi)) for l, lo, hi in s)
    L.append(f"\n  /* Custom pair */\n  --space-s-l: {calc_clamp(sm['s'][0], sm['l'][1], c['minW'], c['maxW'])};")
    L += ["}", "", "/* Optional: ready-made heading styles — remove if not needed */",
          ".fluid-type { font-size: var(--step-0); line-height: 1.6; }"]
    heads = [s_ for s_, _, _ in t if s_ > 0][:6]
    for i, st in enumerate(heads):
        L.append(f".fluid-type h{i+1} {{ font-size: var(--step-{st}); line-height: 1.15; }}")
    L.append("")
    open(os.path.join(out, "utopia", "fluid", f"fluid-{key}.css"), "w").write("\n".join(L))
    summary[key] = {k: v for k, v in c.items()}
    summary[key]["type"] = [{"step": st, "label_tailwind": TYPE_LABEL.get(st), "min_px": r4(lo), "max_px": r4(hi)} for st, lo, hi in t]
    summary[key]["space"] = [{"label": l, "min_px": lo, "max_px": hi} for l, lo, hi in s]
json.dump(summary, open(os.path.join(out, "utopia", "fluid", "fluid-scales.json"), "w"), ensure_ascii=False, indent=1)
print("ok")
